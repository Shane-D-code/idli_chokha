def evaluate_model(y_true, y_pred):

    mae = mean_absolute_error(y_true, y_pred)

    rmse = np.sqrt(
        mean_squared_error(y_true, y_pred)
    )

    r2 = r2_score(y_true, y_pred)

    true_grade = msw_to_grade_ord(y_true)
    pred_grade = msw_to_grade_ord(y_pred)

    within_1 = np.mean(
        np.abs(true_grade - pred_grade) <= 1
    )

    exact = np.mean(
        true_grade == pred_grade
    )

    return {
        'MAE_kt': mae,
        'RMSE_kt': rmse,
        'R2': r2,
        'Within_1_IMD_%': within_1 * 100,
        'Exact_IMD_%': exact * 100
    }


