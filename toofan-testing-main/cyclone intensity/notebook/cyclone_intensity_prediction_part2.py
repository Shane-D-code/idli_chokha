pilot = pilot.copy()

# ------------------------------------------------------------
# 1. Vertical wind shear
# Tropical cyclone intensity is strongly affected by
# differences in wind between lower and upper atmosphere.
# ------------------------------------------------------------

# 850–200 hPa deep-layer wind shear
pilot["era5_shear_850_200"] = np.sqrt(
    (pilot["era5_u200"] - pilot["era5_u850"])**2 +
    (pilot["era5_v200"] - pilot["era5_v850"])**2
)

# 850–500 hPa mid-level shear
pilot["era5_shear_850_500"] = np.sqrt(
    (pilot["era5_u500"] - pilot["era5_u850"])**2 +
    (pilot["era5_v500"] - pilot["era5_v850"])**2
)

# ------------------------------------------------------------
# 2. Wind speed at key levels
# ------------------------------------------------------------

for level in [850, 700, 500, 200]:
    pilot[f"era5_wind_{level}"] = np.sqrt(
        pilot[f"era5_u{level}"]**2 +
        pilot[f"era5_v{level}"]**2
    )

# ------------------------------------------------------------
# 3. Atmospheric temperature differences
# Useful proxies for vertical thermal structure
