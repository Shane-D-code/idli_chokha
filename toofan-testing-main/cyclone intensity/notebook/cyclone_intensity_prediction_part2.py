# --------------------------------------------------
# ROBUST SST REPAIR: nearest valid ocean grid cell
# --------------------------------------------------

def get_nearest_valid_sst(ds, dt, lat, lon, search_radius=5):
    """
    Extract SST at nearest valid ocean grid cell.

    search_radius = number of grid cells around the nearest point.
    ERA5 resolution = 0.25°, so radius 5 searches ~1.25°.
    """

    # Select nearest available time
    time_ds = ds.sel(valid_time=pd.Timestamp(dt), method="nearest")

    # Find nearest grid indices
    lat_values = ds.latitude.values
    lon_values = ds.longitude.values

    lat_idx = np.abs(lat_values - lat).argmin()
    lon_idx = np.abs(lon_values - lon).argmin()

    # First try exact nearest grid point
    value = time_ds["sst"].isel(
        latitude=lat_idx,
        longitude=lon_idx
    ).values

    if np.isfinite(value):
        return float(value) - 273.15

    # Search outward for nearest valid SST
    best_value = np.nan
    best_distance = np.inf

    for i in range(
        max(0, lat_idx - search_radius),
        min(len(lat_values), lat_idx + search_radius + 1)
    ):
        for j in range(
            max(0, lon_idx - search_radius),
            min(len(lon_values), lon_idx + search_radius + 1)
        ):

            candidate = time_ds["sst"].isel(
                latitude=i,
                longitude=j
            ).values

            if np.isfinite(candidate):

                # Approximate geographic distance
                distance = np.sqrt(
                    (lat_values[i] - lat) ** 2 +
                    (lon_values[j] - lon) ** 2
                )

                if distance < best_distance:
                    best_distance = distance
                    best_value = float(candidate)

    if np.isfinite(best_value):
        return best_value - 273.15

    return np.nan


