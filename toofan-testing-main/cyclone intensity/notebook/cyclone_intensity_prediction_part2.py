def get_previous_value(df, value_col, hours, tolerance=3):

    left = df[
        ['storm_id', 'datetime_final']
    ].copy()

    left['lookup_time'] = (
        left['datetime_final']
        - pd.Timedelta(hours=hours)
    )

    right = df[
        ['storm_id', 'datetime_final', value_col]
    ].copy()

    right = right.rename(
        columns={
            'datetime_final': 'previous_datetime',
            value_col: 'previous_value'
        }
    )

    # merge_asof requires sorting by the merge key
    left = left.sort_values(
        ['lookup_time', 'storm_id']
    )

    right = right.sort_values(
        ['previous_datetime', 'storm_id']
    )

    merged = pd.merge_asof(
        left,
        right,
        left_on='lookup_time',
        right_on='previous_datetime',
        by='storm_id',
        direction='backward',
        tolerance=pd.Timedelta(hours=tolerance)
    )

    return (
        merged['previous_value'].values,
        merged['previous_datetime'].values
    )


